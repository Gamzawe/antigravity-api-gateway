import { test } from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { AccessStore } from '../../src/console/access.mjs';

test('owner HTTP flow permits one token-free account only, blocks cross-site writes and key-only management; logout invalidates session', async () => {
  const module = await import('../../src/console/router.mjs').catch(() => null);
  assert.ok(module?.createConsole, 'owner console HTTP routes must exist');
  const dir = mkdtempSync(join(process.env.TMPDIR || tmpdir(), 'agw-routes-'));
  const store = new AccessStore(dir);
  const app = express();
  const origin = 'http://localhost:8089';
  app.use('/console', module.createConsole({ store, publicUrl: origin }));
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}/console`;
  const send = (path, body, extra = {}) => fetch(base + '/api/' + path, { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json', ...extra }, body: JSON.stringify(body) });
  try {
    let r = await fetch(base + '/api/session');
    assert.equal((await r.json()).configured, false);
    assert.equal((await fetch(base + '/api/keys')).status, 401);
    const data = { username: 'owner', password: 'test-password-with-length' };
    assert.equal((await send('setup', data, { Origin: 'https://evil.test' })).status, 403);
    assert.equal((await send('setup', { ...data, password: 'short' })).status, 400);
    assert.equal((await send('setup', data)).status, 201);
    assert.equal((await send('setup', { username: 'intruder', password: 'another-strong-password' })).status, 409);
    assert.equal((await send('login', { username: 'other', password: data.password })).status, 401);
    r = await send('login', data);
    assert.equal(r.status, 200);
    const cookie = r.headers.get('set-cookie').split(';')[0];
    assert.match(r.headers.get('set-cookie'), /HttpOnly/);
    assert.match(r.headers.get('set-cookie'), /SameSite=Strict/);
    const session = await r.json();
    assert.ok(session.csrf);
    assert.equal((await send('keys', { name: 'phone' }, { Cookie: cookie })).status, 403);
    assert.equal((await send('keys', { name: 'phone' }, { Cookie: cookie, 'X-CSRF-Token': session.csrf, Origin: 'https://evil.test' })).status, 403);
    r = await send('keys', { name: 'phone' }, { Cookie: cookie, 'X-CSRF-Token': session.csrf });
    assert.equal(r.status, 201);
    const created = await r.json();
    assert.ok(store.verifyKey(created.key));
    assert.equal((await fetch(base + '/api/keys', { headers: { Authorization: 'Bearer ' + created.key } })).status, 401);
    r = await fetch(base + '/api/keys', { headers: { Cookie: cookie } });
    const list = await r.json();
    assert.equal(list.keys.length, 1);
    assert.ok(!JSON.stringify(list).includes(created.key));
    r = await fetch(base + '/api/keys/' + created.id, { method: 'DELETE', headers: { Origin: origin, Cookie: cookie, 'X-CSRF-Token': session.csrf } });
    assert.equal(r.status, 200);
    assert.equal(store.verifyKey(created.key), null);
    assert.equal((await send('logout', {}, { Cookie: cookie, 'X-CSRF-Token': session.csrf })).status, 200);
    assert.equal((await fetch(base + '/api/keys', { headers: { Cookie: cookie } })).status, 401);
    for (let i = 0; i < 9; i++) r = await send('login', { username: 'owner', password: 'bad' });
    assert.equal(r.status, 429);
    const page = await fetch(base + '/');
    assert.match(page.headers.get('content-security-policy'), /frame-ancestors 'none'/);
    assert.equal(page.headers.get('cache-control'), 'no-store');
  } finally { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); rmSync(dir, { recursive: true, force: true }); }
});
