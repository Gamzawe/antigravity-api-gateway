import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fixture, evidenceDir, newPassword } from './console-test-fixture.mjs';

// Isolated test owner only: no user password or saved browser account is involved.
const f = await fixture();
let browser;
try {
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const staleContext = await browser.newContext();
  const stalePage = await staleContext.newPage();
  await stalePage.goto(f.base + '/console/');
  await stalePage.locator('#auth-view').waitFor({ state: 'visible' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const password = newPassword();
  await page.goto(f.base + '/console/');
  await page.locator('#auth-view').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#setup-token').count(), 0, 'setup token input must not exist');
  assert.equal(await page.locator('#auth-form input').count(), 2, 'setup asks only for username and password');
  assert.match(await page.locator('#auth-title').innerText(), /Create your owner account/);
  await page.locator('#username').fill('browser-test-owner');
  await page.locator('#password').fill(password);
  await page.locator('#auth-submit').click();
  await page.locator('#dashboard').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#empty-state').isVisible(), true);
  await stalePage.locator('#username').fill('browser-test-owner');
  await stalePage.locator('#password').fill(password);
  await stalePage.locator('#auth-submit').click();
  await stalePage.waitForFunction(() => !document.getElementById('auth-submit').disabled);
  assert.equal(await stalePage.locator('#auth-submit').innerText(), 'Sign in', 'stale setup page must recover to login after another tab claims the owner');
  await stalePage.locator('#auth-submit').click();
  await stalePage.locator('#dashboard').waitFor({ state: 'visible' });
  await staleContext.close();
  await page.locator('#open-create').click();
  await page.locator('#key-name').fill('My phone');
  await page.locator('#create-submit').click();
  await page.locator('#secret-dialog').waitFor({ state: 'visible' });
  const key = await page.locator('#new-key').inputValue();
  assert.match(key, /^sk-agw-/);
  await page.locator('#copy-key').click();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), key);
  assert.equal((await fetch(f.base + '/v1/key-check', { headers: { Authorization: 'Bearer ' + key } })).status, 200);
  // Screenshot only after clearing the one-time secret; no test secrets in artifacts.
  await page.locator('#close-secret').click();
  assert.equal((await page.locator('#new-key').inputValue()).length === 0, true, 'one-time key must be cleared');
  await page.locator('#copy-url').click();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), f.origin + '/v1');
  await page.locator('details').filter({ hasText: 'Quick API example' }).locator('summary').click();
  await page.locator('#copy-example').click();
  assert.match(await page.evaluate(() => navigator.clipboard.readText()), /chat\/completions/);
  // Clear clipboard after verification.
  await page.evaluate(() => navigator.clipboard.writeText(''));
  mkdirSync(evidenceDir, { recursive: true });
  await page.screenshot({ path: join(evidenceDir, 'console-desktop.png'), fullPage: true });
  await page.locator('#logout').click();
  await page.locator('#auth-view').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#auth-title').innerText(), 'Welcome back.');
  assert.equal(await page.locator('#auth-submit').innerText(), 'Sign in');
  const duplicate = await fetch(f.base + '/console/api/setup', { method: 'POST', headers: { Origin: f.origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'second-owner', password: newPassword() }) });
  assert.equal(duplicate.status, 409, 'second account creation must be closed');
  await page.locator('#username').fill('browser-test-owner');
  await page.locator('#password').fill(password);
  await page.locator('#auth-submit').click();
  await page.locator('#dashboard').waitFor({ state: 'visible' });
  await page.reload();
  await page.locator('#dashboard').waitFor({ state: 'visible' });
  assert.match(await page.locator('#keys-body').innerText(), /My phone/);
  await page.setViewportSize({ width: 390, height: 844 });
  const overflow = await page.evaluate(() => ({ page: document.documentElement.scrollWidth, viewport: innerWidth, elements: [...document.querySelectorAll('body *')].filter(e => !e.closest('dialog') && e.getBoundingClientRect().right > innerWidth).map(e => ({ tag: e.tagName, id: e.id, class: e.className, right: e.getBoundingClientRect().right, width: e.getBoundingClientRect().width })).slice(0, 18) }));
  if (overflow.page > overflow.viewport) console.log(JSON.stringify(overflow));
  assert.equal(overflow.page <= overflow.viewport, true, 'mobile viewport must not overflow horizontally');
  const mobileControlsFit = await page.locator('#keys-body tr').first().evaluate(row => {
    const name = row.querySelector('td').getBoundingClientRect();
    const action = row.querySelector('button').getBoundingClientRect();
    return name.left >= 0 && name.right <= innerWidth && action.left >= 0 && action.right <= innerWidth;
  });
  assert.equal(mobileControlsFit, true, 'mobile key name and revoke action must be visible together');
  await page.locator('#open-create').click();
  await page.locator('#key-name').fill('Mobile editor');
  await page.locator('#create-submit').click();
  await page.locator('#secret-dialog').waitFor({ state: 'visible' });
  await page.locator('#close-secret').click();
  await page.locator('#keys-body button[aria-label="Revoke My phone"]').click();
  await page.locator('#confirm-revoke').click();
  await page.locator('#revoke-dialog').waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.getElementById('notice').textContent.includes('Key revoked'));
  assert.equal((await fetch(f.base + '/v1/key-check', { headers: { Authorization: 'Bearer ' + key } })).status, 401);
  await page.locator('#models-details summary').click();
  await page.waitForFunction(() => /Unable|No models/.test(document.getElementById('models-status').textContent));
  assert.match(await page.locator('#models-status').innerText(), /Unable|No models/);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: join(evidenceDir, 'console-mobile.png'), fullPage: true });
  assert.deepEqual(errors, []);
  const partial = await fixture();
  try {
    const partialContext = await browser.newContext();
    const partialPage = await partialContext.newPage();
    partialPage.on('pageerror', error => errors.push(error.message));
    let setupCalls = 0;
    partialPage.on('request', request => { if (request.url().endsWith('/console/api/setup') && request.method() === 'POST') setupCalls++; });
    await partialPage.route('**/console/api/login', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: 'Synthetic transient login failure' } }) }), { times: 1 });
    await partialPage.goto(partial.base + '/console/');
    await partialPage.locator('#auth-view').waitFor({ state: 'visible' });
    await partialPage.locator('#username').fill('partial-setup-owner');
    await partialPage.locator('#password').fill(newPassword());
    await partialPage.locator('#auth-submit').click();
    await partialPage.waitForFunction(() => !document.getElementById('auth-submit').disabled);
    assert.equal(await partialPage.locator('#auth-submit').innerText(), 'Sign in', 'created account must show login even when automatic login fails');
    assert.match(await partialPage.locator('#notice').innerText(), /Synthetic transient login failure/);
    await partialPage.locator('#auth-submit').click();
    await partialPage.locator('#dashboard').waitFor({ state: 'visible' });
    assert.equal(setupCalls, 1, 'login recovery must not retry account creation');
    await partialContext.close();
  } finally { await partial.close(); }
  assert.deepEqual(errors, []);
  writeFileSync(join(evidenceDir, 'browser.json'), JSON.stringify({ verifiedAt: new Date().toISOString(), engine: 'Playwright Chromium', desktop: [1280, 900], mobile: [390, 844], checks: ['token-free-single-owner-setup', 'duplicate-setup-refused', 'stale-setup-tab-recovery', 'setup-login-failure-recovery', 'login', 'logout', 'session-refresh', 'create-key', 'one-time-reveal', 'copy-key', 'copy-url', 'copy-example', 'revoke-key', 'mobile-create', 'no-horizontal-overflow', 'upstream-failure-state'], pageErrors: errors }, null, 2));
} finally { if (browser) await browser.close(); await f.close(); }
console.log('CONSOLE_BROWSER_OK');
